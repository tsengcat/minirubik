/* Writes the four search tables as a C header, so a solver can link them in
 * as read-only data instead of building them at run time. See
 * host/ida_draft/README.md.
 *
 * It includes ida_test.c and calls its build_tables, so the tables written
 * here come from the same code that ida_test checks against the exact BFS.
 *
 * Build and run from the repository root:
 *   cc -O2 -std=c99 -Wall -Wextra -o host/ida_draft/emit_tables \
 *       host/ida_draft/emit_tables.c
 *   ./host/ida_draft/emit_tables > tables.h
 */

#define main ida_test_main
#include "ida_test.c"
#undef main

/* Prints a [rows][cols] table, or a [cols] one when rows is 1, as a C array
 * definition. wide selects uint16_t data over uint8_t.
 */
static void emit(const char *name, const void *data, int wide, unsigned rows,
                 unsigned cols)
{
    unsigned per_line = wide ? 12 : 24;
    const char *indent = rows > 1 ? "        " : "    ";
    printf("static const %s %s", wide ? "uint16_t" : "uint8_t", name);
    if (rows > 1)
        printf("[%u]", rows);
    printf("[%u] = {\n", cols);
    for (unsigned r = 0; r < rows; ++r) {
        if (rows > 1)
            puts("    {");
        for (unsigned c = 0; c < cols; ++c) {
            unsigned i = r * cols + c;
            unsigned value = wide ? ((const uint16_t *) data)[i]
                                  : ((const uint8_t *) data)[i];
            if (c % per_line == 0)
                fputs(indent, stdout);
            printf("%u,", value);
            putchar(c % per_line == per_line - 1 || c + 1 == cols ? '\n'
                                                                  : ' ');
        }
        if (rows > 1)
            puts("    },");
    }
    puts("};\n");
}

int main(void)
{
    build_tables();
    for (uint16_t p = 0; p < PERMUTATIONS; ++p)
        if (perm_dist[p] == UINT8_MAX) {
            fputs("permutation table not fully populated\n", stderr);
            return 1;
        }
    for (uint16_t o = 0; o < ORIENTATIONS; ++o)
        if (ori_dist[o] == UINT8_MAX) {
            fputs("orientation table not fully populated\n", stderr);
            return 1;
        }

    puts("/* Generated by host/ida_draft/emit_tables.c. Do not edit.\n"
         " *\n"
         " * perm_turn[f][p], ori_turn[f][o]: one quarter turn of face f, "
         "0 R, 1 B, 2 D.\n"
         " * perm_dist[p], ori_dist[o]: moves to solved in each "
         "projection.");
    printf(" * Static data: %zu + %zu + %zu + %zu = %zu bytes.\n */\n\n",
           sizeof perm_turn, sizeof ori_turn, sizeof perm_dist,
           sizeof ori_dist,
           sizeof perm_turn + sizeof ori_turn + sizeof perm_dist +
               sizeof ori_dist);
    puts("#ifndef TABLES_H\n#define TABLES_H\n\n#include <stdint.h>\n");
    emit("perm_turn", perm_turn, 1, 3, PERMUTATIONS);
    emit("ori_turn", ori_turn, 1, 3, ORIENTATIONS);
    emit("perm_dist", perm_dist, 0, 1, PERMUTATIONS);
    emit("ori_dist", ori_dist, 0, 1, ORIENTATIONS);
    puts("#endif");

    if (fflush(stdout) != 0 || ferror(stdout)) {
        fputs("could not write the tables\n", stderr);
        return 1;
    }
    return 0;
}
